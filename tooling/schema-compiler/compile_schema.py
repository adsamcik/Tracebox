def _kotlin_name(name: str) -> str:
    return name[:1].lower() + name[1:]


def _kotlin_camel_name(name: str) -> str:
    first, *rest = name.split("_")
    return first + "".join(part[:1].upper() + part[1:] for part in rest)


def _direct_boot_projection(schema) -> tuple[dict, str]:
    direct_boot_events = [event for event in schema.events if event.direct_boot_eligible]
    if len(direct_boot_events) != 1:
        raise SchemaError("Direct Boot v2 requires exactly one generated C0 event")
    event = direct_boot_events[0]
    projection = {
        "projection_version": 1,
        "event": {
            "id": event.id,
            "name": event.name,
            "category": event.category,
            "retention": event.retention,
            "package_visibility": event.package_visibility,
            "direct_boot_eligible": event.direct_boot_eligible,
            "category_mask": 1 << schema.events.index(event),
            "fields": [field.__dict__ for field in event.fields],
        },
    }
    canonical = json.dumps(
        projection,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    return projection, hashlib.sha256(canonical).hexdigest()


def render(schema, fingerprint: str) -> dict[str, str]:
    kotlin_types = {"u16": "UShort", "u32": "UInt", "u64": "ULong", "i32": "Int", "enum": "UInt", "fixed32": "UInt", "bounded_utf8": "String"}
    c_types = {"u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t", "i32": "int32_t", "enum": "uint32_t", "fixed32": "uint32_t", "bounded_utf8": "tb_utf8_view_v1"}
