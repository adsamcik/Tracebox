"""Generate all Phase 1 schema consumers from one strict JSON model."""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tooling" / "schema-model"))
from schema_model import SchemaError, parse_schema  # noqa: E402


def render(schema, fingerprint: str) -> dict[str, str]:
    metadata = {
        "schema_version": schema.version,
        "fingerprint": fingerprint,
        "events": [
            {
                "id": event.id, "name": event.name, "category": event.category,
                "retention": event.retention, "package_visibility": event.package_visibility,
                "direct_boot_eligible": event.direct_boot_eligible,
                "fields": [field.__dict__ for field in event.fields],
            } for event in schema.events
        ],
    }
    kotlin = """// Generated by tooling/schema-compiler/compile_schema.py. Do not edit.
package dev.tracebox.api.generated

enum class GeneratedEventId(val stableId: Int) {
""" + "".join(f"    {event.name.upper()}({event.id}),\n" for event in schema.events) + "}\n"
    c = """/* Generated by tooling/schema-compiler/compile_schema.py. Do not edit. */
#ifndef TRACEBOX_GENERATED_EVENTS_H_
#define TRACEBOX_GENERATED_EVENTS_H_
#include <stdint.h>
typedef enum {
""" + "".join(f"  TB_EVENT_{event.name.upper()} = {event.id},\n" for event in schema.events) + """} tb_event_id_v1;
typedef enum { TB_PROCESS_ROLE_APP = 1, TB_THREAD_ROLE_UNKNOWN = 0 } tb_generated_role_v1;
#endif
"""
    rust = """// Generated by tooling/schema-compiler/compile_schema.py. Do not edit.
pub const SCHEMA_FINGERPRINT: &str = \"""" + fingerprint + """\";
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EventId {
""" + "".join(f"    {event.name} = {event.id},\n" for event in schema.events) + "}\n"
    proto = """// Generated protobuf-compatible definitions. No free-form values.\nsyntax = \"proto3\";\npackage tracebox.generated;\n""" + "".join(
        "message " + event.name + " {\n" + "".join(
            f"  uint64 {field.name} = {field.id};\n" for field in event.fields
        ) + "}\n" for event in schema.events
    )
    labels = {
        event.name: f"{event.category}: includes only " +
        ", ".join(f"{field.privacy} {field.name}" for field in event.fields)
        for event in schema.events
    }
    docs = "# Generated Tracebox schema reference\n\n"
    for event in schema.events:
        docs += f"## {event.name} (`{event.id}`)\n\n"
        docs += f"Category: `{event.category}`; retention: `{event.retention}`; package: `{event.package_visibility}`; Direct Boot: `{event.direct_boot_eligible}`.\n\n"
        docs += "| Field ID | Field | Privacy | Type | Maximum encoded size | Transformation |\n|---:|---|---|---|---:|---|\n"
        docs += "".join(f"| {field.id} | {field.name} | {field.privacy} | {field.semantic_type} | {field.max_encoded_size} | {field.transform} |\n" for field in event.fields)
        docs += "\n"
    return {
        "android/tracebox-api/src/main/kotlin/dev/tracebox/api/generated/GeneratedSchema.kt": kotlin,
        "native/include/tracebox/generated_events.h": c,
        "rust/tracebox-sys/src/generated.rs": rust,
        "schema/generated/tracebox_records.proto": proto,
        "schema/generated/decoder-metadata.json": json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        "schema/generated/disclosure-labels.json": json.dumps(labels, indent=2, sort_keys=True) + "\n",
        "docs/generated/schema-reference.md": docs,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=pathlib.Path, default=ROOT / "schema" / "events.json")
    parser.add_argument("--out", type=pathlib.Path, default=ROOT)
    args = parser.parse_args()
    raw = args.schema.read_bytes()
    try:
        schema = parse_schema(json.loads(raw), raw.decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, SchemaError) as error:
        print(f"schema compilation failed: {error}", file=sys.stderr)
        return 1
    fingerprint = hashlib.sha256(raw).hexdigest()
    for relative, content in render(schema, fingerprint).items():
        target = args.out / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    print(f"schema fingerprint {fingerprint}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
